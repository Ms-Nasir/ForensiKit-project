@app.route('/api/metadata', methods=['POST'])
def api_metadata():
    from PIL import Image
    from PIL.ExifTags import TAGS, GPSTAGS
    import datetime

    data = request.json
    filename = data.get('filename', '')
    filepath = os.path.join('./output', filename)

    if not os.path.exists(filepath):
        return jsonify({'error': 'File not found!'})

    # Basic file info — works for ALL files
    stat = os.stat(filepath)
    result = {
        'filename': filename,
        'size': str(round(stat.st_size / 1024, 2)) + ' KB',
        'created': str(datetime.datetime.fromtimestamp(stat.st_ctime).strftime('%Y-%m-%d %H:%M:%S')),
        'modified': str(datetime.datetime.fromtimestamp(stat.st_mtime).strftime('%Y-%m-%d %H:%M:%S')),
        'type': filename.rsplit('.', 1)[-1].upper() if '.' in filename else 'Unknown',
        'exif': {},
        'gps': None
    }

    # Try to read EXIF data — only works for images
    try:
        img = Image.open(filepath)
        result['width'] = img.width
        result['height'] = img.height
        result['format'] = img.format

        # Read EXIF tags
        exif_data = img._getexif()
        if exif_data:
            for tag_id, value in exif_data.items():
                tag = TAGS.get(tag_id, tag_id)

                # Skip binary/complex data
                if isinstance(value, (str, int, float)):
                    result['exif'][str(tag)] = str(value)

            # Try to read GPS data
            gps_info = {}
            for tag_id, value in exif_data.items():
                tag = TAGS.get(tag_id, tag_id)
                if tag == 'GPSInfo':
                    for gps_tag_id, gps_value in value.items():
                        gps_tag = GPSTAGS.get(gps_tag_id, gps_tag_id)
                        gps_info[gps_tag] = str(gps_value)
            if gps_info:
                result['gps'] = gps_info

    except Exception:
        result['note'] = 'Not an image or no EXIF data found'

    return jsonify(result)



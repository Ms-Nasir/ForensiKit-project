@app.route('/api/extract', methods=['POST'])
def api_extract():
    # Get the path user selected
    data = request.json
    path = data.get('path', '/sdcard/')

    # Try to pull files from phone using ADB
    try:
        result = subprocess.run(
            ['adb', 'pull', path, './output/'],
            capture_output=True,
            text=True,
            timeout=30
        )
        return jsonify({'message': 'Files extracted successfully! Check output folder.'})

    except FileNotFoundError:
        # ADB not installed — demo mode
        os.makedirs('./output', exist_ok=True)
        with open('./output/demo_file.txt', 'w') as f:
            f.write('This is a demo extracted file.')
        return jsonify({'message': 'Demo mode — ADB not found. A demo file was created in output folder.'})

    except Exception as e:
        return jsonify({'message': 'Error: ' + str(e)})
    
@app.route('/api/report', methods=['POST'])
def api_report():
    import hashlib
    import datetime
    from reportlab.lib.pagesizes import A4
    from reportlab.lib import colors
    from reportlab.lib.units import cm
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
    from reportlab.lib.styles import getSampleStyleSheet

    data = request.json
    case_name = data.get('case_name', 'Unknown')
    investigator = data.get('investigator', 'Unknown')

    os.makedirs('./output', exist_ok=True)

    # Collect all files with hashes
    files_data = []
    for filename in os.listdir('./output'):
        full_path = os.path.join('./output', filename)
        if os.path.isfile(full_path):
            # Generate hash for each file
            sha256 = hashlib.sha256()
            with open(full_path, 'rb') as f:
                for chunk in iter(lambda: f.read(4096), b''):
                    sha256.update(chunk)
            files_data.append({
                'name': filename,
                'size': str(round(os.path.getsize(full_path) / 1024, 2)) + ' KB',
                'hash': sha256.hexdigest()
            })

    # Build the PDF
    pdf_path = './output/forensic_report.pdf'
    doc = SimpleDocTemplate(pdf_path, pagesize=A4,
                             rightMargin=2*cm, leftMargin=2*cm,
                             topMargin=2*cm, bottomMargin=2*cm)
    styles = getSampleStyleSheet()
    story = []

    # Title
    story.append(Paragraph("🔍 Mobile Forensics Report", styles['Title']))
    story.append(Spacer(1, 12))

    # Case info table
    now = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    info_data = [
        ['Case Name', case_name],
        ['Investigator', investigator],
        ['Report Generated', now],
        ['Total Files', str(len(files_data))],
    ]
    info_table = Table(info_data, colWidths=[5*cm, 10*cm])
    info_table.setStyle(TableStyle([
        ('FONTSIZE', (0,0), (-1,-1), 10),
        ('FONTNAME', (0,0), (0,-1), 'Helvetica-Bold'),
        ('BACKGROUND', (0,0), (0,-1), colors.lightgrey),
        ('GRID', (0,0), (-1,-1), 0.5, colors.grey),
        ('PADDING', (0,0), (-1,-1), 6),
    ]))
    story.append(info_table)
    story.append(Spacer(1, 20))

    # Files table
    story.append(Paragraph("Extracted Files & Hashes", styles['Heading2']))
    story.append(Spacer(1, 8))

    if files_data:
        file_table_data = [['File Name', 'Size', 'SHA-256 Hash']]
        for f in files_data:
            file_table_data.append([f['name'], f['size'], f['hash'][:40] + '...'])

        ft = Table(file_table_data, colWidths=[5*cm, 2.5*cm, 7.5*cm])
        ft.setStyle(TableStyle([
            ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
            ('FONTSIZE', (0,0), (-1,-1), 8),
            ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#1a1a2e')),
            ('TEXTCOLOR', (0,0), (-1,0), colors.white),
            ('GRID', (0,0), (-1,-1), 0.3, colors.grey),
            ('PADDING', (0,0), (-1,-1), 5),
        ]))
        story.append(ft)
    else:
        story.append(Paragraph("No files found.", styles['Normal']))

    story.append(Spacer(1, 20))
    story.append(Paragraph("Generated by ForensiKit — Mobile Forensics Tool", styles['Normal']))

    doc.build(story)

    return jsonify({
        'message': 'PDF report generated successfully!',
        'filename': 'forensic_report.pdf'
    })

@app.route('/api/recover')
def api_recover():
    recovered = []

    if not os.path.exists('./output'):
        return jsonify({'files': [], 'count': 0})

    # Walk through every file in output folder
    for filename in os.listdir('./output'):
        full_path = os.path.join('./output', filename)

        if os.path.isfile(full_path):
            reason = None

            # Check 1: hidden file (starts with a dot)
            if filename.startswith('.'):
                reason = 'Hidden file'

            # Check 2: temp or deleted file
            elif filename.endswith('.tmp'):
                reason = 'Temporary file'

            elif filename.endswith('.bak'):
                reason = 'Backup file'

            elif filename.endswith('.deleted'):
                reason = 'Marked as deleted'

            # Check 3: zero byte file (wiped)
            elif os.path.getsize(full_path) == 0:
                reason = 'Empty/wiped file'

            if reason:
                recovered.append({
                    'name': filename,
                    'reason': reason,
                    'size': str(os.path.getsize(full_path)) + ' bytes'
                })

    return jsonify({'files': recovered, 'count': len(recovered)})

from werkzeug.utils import secure_filename

ALLOWED_EXTENSIONS = {'txt', 'pdf', 'png', 'jpg', 'jpeg', 'db', 'csv', 'bak', 'tmp', 'log', 'pptx', 'docx', 'xlsx', 'mp4', 'zip'}

def allowed_file(filename):
    return '.' in filename and filename.rsplit('.', 1)[1].lower() in ALLOWED_EXTENSIONS

